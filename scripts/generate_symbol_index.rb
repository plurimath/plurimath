# frozen_string_literal: true

# Generates lib/plurimath/math/symbol_index.rb, the static index that lets
# Plurimath::Math::Symbols load its classes on demand instead of requiring
# all symbol files the first time the namespace is touched.
#
# Usage:
#   bundle exec ruby scripts/generate_symbol_index.rb [--check]
#
#   --check   do not write; exit 1 when the committed index is out of date.
#
# The index records what the old eager loader produced: the classes in the
# order they were defined (Symbol and Paren descendants), the file of every
# constant, the n-ary symbols, and each class's INPUT strings per language.
# Utility rebuilds its lookup tables from this data in the same order, so
# the tables, and every lookup made through them, stay the same.

$LOAD_PATH.unshift(File.expand_path("../lib", __dir__))
require "plurimath"

ROOT = File.expand_path("../lib/plurimath/math", __dir__)
SYMBOLS_DIR = File.join(ROOT, "symbols")
INDEX_FILE = File.join(ROOT, "symbol_index.rb")

def load_all_in_definition_order
  # The order the eager loader used: the Symbol base, then every top-level
  # symbol file, then the nested family files, each sorted by path.
  Plurimath::Math::Symbols::Symbol
  files = Dir.glob(File.join(SYMBOLS_DIR, "*.rb")) +
    Dir.glob(File.join(SYMBOLS_DIR, "*", "*.rb"))
  files.each { |file| require file }
end

def relative_name(klass)
  klass.name.delete_prefix("Plurimath::Math::Symbols::")
end

def relative_file(name)
  path = Object.const_source_location("Plurimath::Math::Symbols::#{name}")&.first
  raise "no source for #{name}" unless path&.start_with?(SYMBOLS_DIR)

  path.delete_prefix("#{SYMBOLS_DIR}/").delete_suffix(".rb")
end

def literal(value)
  case value
  when Array then "[#{value.map { |item| literal(item) }.join(', ')}]"
  when String, Symbol, nil then value.inspect
  else raise "unexpected INPUT value #{value.inspect}"
  end
end

def build
  load_all_in_definition_order
  symbols = Plurimath::Math::Symbols::Symbol.descendants.map { |k| relative_name(k) }
  parens = Plurimath::Math::Symbols::Paren.descendants.map { |k| relative_name(k) }
  classes = symbols + parens
  nary = symbols.select do |name|
    Plurimath::Math::Symbols.const_get(name).new.is_nary_symbol?
  end
  langs = classes.flat_map { |name| Plurimath::Math::Symbols.const_get(name)::INPUT.keys }.uniq

  out = +<<~RUBY
    # frozen_string_literal: true

    # Generated by scripts/generate_symbol_index.rb. Do not edit by hand;
    # regenerate after adding, removing or changing a symbol class.
    module Plurimath
      module Math
        module SymbolIndex
  RUBY
  out << "      # Constant => file (relative to math/symbols), top-level symbols.\n"
  out << "      FILES = {\n"
  symbols.each { |name| out << "        #{name.inspect} => #{relative_file(name).inspect},\n" }
  out << "      }.freeze\n\n"
  out << "      # Constant => file for the classes nested in Paren.\n"
  out << "      PAREN_FILES = {\n"
  parens.each do |name|
    out << "        #{name.split('::').last.inspect} => #{relative_file(name).inspect},\n"
  end
  out << "      }.freeze\n\n"
  out << "      # Symbol.descendants and Paren.descendants in definition order.\n"
  out << "      SYMBOLS = #{literal(symbols)}.freeze\n"
  out << "      PARENS = #{literal(parens)}.freeze\n\n"
  out << "      # Symbols whose instances answer is_nary_symbol? with true.\n"
  out << "      NARY = #{literal(nary)}.freeze\n\n"
  out << "      # INPUT[lang].flatten per class, for classes that define the lang.\n"
  out << "      INPUTS = {\n"
  langs.each do |lang|
    out << "        #{lang.inspect} => {\n"
    classes.each do |name|
      input = Plurimath::Math::Symbols.const_get(name)::INPUT[lang]
      next if input.nil?

      out << "          #{name.inspect} => #{literal(input.flatten)}.freeze,\n"
    end
    out << "        }.freeze,\n"
  end
  out << "      }.freeze\n"
  out << "    end\n  end\nend\n"
  out
end

content = build
if ARGV.include?("--check")
  current = File.exist?(INDEX_FILE) ? File.binread(INDEX_FILE) : ""
  if current == content.b
    puts "symbol index is up to date"
  else
    warn "symbol index is out of date; run scripts/generate_symbol_index.rb"
    exit 1
  end
else
  File.binwrite(INDEX_FILE, content)
  puts "wrote #{INDEX_FILE}"
end
