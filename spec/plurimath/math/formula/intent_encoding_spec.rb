def unicodemath_examples_intents(array)
  array.scan(/intent="([^"]+)"/).sort.join
    .gsub("$n)", "$naryand)")
    .gsub("𝐴", "A")
    .gsub("𝑎", "a")
    .gsub("𝛼", "a")
    .gsub("𝑏", "b")
    .gsub("𝑆", "S")
    .gsub("𝑛", "n")
    .gsub("𝑘", "k")
    .gsub("𝑡", "t")
    .gsub("𝑥", "x")
    .gsub("𝑦", "y")
    .gsub("𝑁", "N")
    .gsub("α", "a")
    .gsub("𝜋", "π")
end
